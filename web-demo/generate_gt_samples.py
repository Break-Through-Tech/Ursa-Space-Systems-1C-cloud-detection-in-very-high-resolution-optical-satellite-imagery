"""
Build the "hand-checked ground truth" samples for the web demo.

For each chosen crop it reads:
  <crops>/<split>/<crop>/image.png       the RGB crop (2048x2048)
  <crops>/<split>/<crop>/mask_gt.png     hand-fixed mask: 0 clear, 255 cloud, 64 smoke, 128 unsure
  <ocm_preds>/<crop>.tif                 OCM's untouched prediction: 0 clear, 1 thick, 2 thin, 3 shadow, 255 no-data

and writes, into web-demo/samples/:
  gt_<crop>_orig.jpg     the crop
  gt_<crop>_gt.jpg       ground truth overlay (cloud blue, smoke orange, unsure grey)
  gt_<crop>_omni.jpg     OCM overlay (cloud red, thick + thin merged, like the benchmark)

plus web-demo/gt_samples_data.js with the manifest and cloud-cover numbers.

Usage:
  python generate_gt_samples.py --crops <ursaspace1C_data/crops> --ocm <_ocm_predictions> [--size 1024]
"""
import argparse
import json
from pathlib import Path

import numpy as np
from PIL import Image

Image.MAX_IMAGE_PIXELS = None
HERE = Path(__file__).resolve().parent

# Picked to show a range of cases: mixed cloud, smoke, clear ground, and places where OCM is wrong.
CHOSEN = [
    ("test", "test_03_c1", "Kelowna: broken cloud over terrain",
     "Mixed scene. The hand fix trims OCM's cloud edges."),
    ("val", "val_39_c1", "Yellowknife: half cloud, half ground",
     "About half the crop is cloud. A good test of where cloud edges are drawn."),
    ("test", "test_01_c1", "Kelowna: wildfire smoke",
     "Almost all smoke. OCM calls it cloud. Our labels keep smoke separate."),
    ("val", "val_17_c1", "Yellowknife: cloud and smoke together",
     "Cloud and smoke in the same crop."),
    ("test", "test_05_c2", "Kelowna: clear ground OCM calls thin cloud",
     "OCM marks the whole crop as thin cloud. The hand check found no cloud."),
    ("test", "test_12_c1", "Kelowna: clear ground",
     "Control crop with no cloud. OCM agrees."),
]

GT_COLORS = {255: (56, 139, 253), 64: (255, 140, 0), 128: (160, 160, 160)}  # cloud, smoke, unsure
OCM_COLOR = (248, 81, 73)
ALPHA = 0.55


def blend(rgb, mask, color):
    out = rgb.astype(np.float32)
    out[mask] = (1 - ALPHA) * out[mask] + ALPHA * np.array(color, np.float32)
    return out.astype(np.uint8)


def pct(mask, valid=None):
    if valid is None:
        return round(100 * float(mask.mean()), 2)
    return round(100 * float(mask[valid].mean()), 2) if valid.any() else 0.0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--crops", required=True)
    ap.add_argument("--ocm", required=True)
    ap.add_argument("--size", type=int, default=1024, help="output width/height in pixels")
    args = ap.parse_args()

    out_dir = HERE / "samples"
    out_dir.mkdir(exist_ok=True)
    manifest = []
    for split, crop, title, desc in CHOSEN:
        folder = Path(args.crops) / split / crop
        rgb = np.array(Image.open(folder / "image.png").convert("RGB"))
        gt = np.array(Image.open(folder / "mask_gt.png"))
        ocm = np.array(Image.open(Path(args.ocm) / f"{crop}.tif"))
        if ocm.ndim == 3:
            ocm = ocm[..., 0]
        assert gt.shape == rgb.shape[:2] == ocm.shape, f"{crop}: size mismatch"

        gt_img = rgb
        for value, color in GT_COLORS.items():
            gt_img = blend(gt_img, gt == value, color)
        ocm_cloud = np.isin(ocm, [1, 2])
        ocm_img = blend(rgb, ocm_cloud, OCM_COLOR)

        files = {}
        for key, arr in (("orig", rgb), ("gt", gt_img), ("omni", ocm_img)):
            name = f"gt_{crop}_{key}.jpg"
            Image.fromarray(arr).resize((args.size, args.size), Image.LANCZOS).save(
                out_dir / name, quality=88)
            files[key] = f"samples/{name}"

        manifest.append({
            "id": f"gt_{crop}",
            "kind": "gt",
            "title": title,
            "desc": desc,
            "crop": crop,
            "split": split,
            **files,
            "metrics": {
                "gt": pct(gt == 255),
                "gt_smoke": pct(gt == 64),
                "omni": pct(ocm_cloud, ocm != 255),
            },
        })
        print(f"{crop}: cloud {manifest[-1]['metrics']['gt']}%, smoke {manifest[-1]['metrics']['gt_smoke']}%, "
              f"OCM {manifest[-1]['metrics']['omni']}%")

    js = "// Generated by generate_gt_samples.py. Do not edit by hand.\n"
    js += "const GT_SAMPLES_MANIFEST = " + json.dumps(manifest, indent=2) + ";\n"
    (HERE / "gt_samples_data.js").write_text(js, encoding="utf-8")
    print(f"wrote {len(manifest)} samples")


if __name__ == "__main__":
    main()
